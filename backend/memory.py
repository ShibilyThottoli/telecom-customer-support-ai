class ChatMessage(TypedDict):
    role: str
    content: str


def _connect() -> sqlite3.Connection | psycopg.Connection:
    database_url = os.environ.get("DATABASE_URL")
    if database_url:
        if database_url.startswith("postgres://"):
            database_url = "postgresql://" + database_url[len("postgres://"):]
        return psycopg.connect(database_url)

    default_path = Path(__file__).resolve().with_name("chat_memory.sqlite3")
    database_path = Path(
        os.environ.get("CHAT_MEMORY_DB_PATH", str(default_path))
    ).expanduser()
    database_path.parent.mkdir(parents=True, exist_ok=True)

    return sqlite3.connect(database_path, timeout=10)


@contextmanager
def _connection():
    connection = _connect()
    is_postgres = not isinstance(connection, sqlite3.Connection)
    try:
        with connection:
            if is_postgres:
                connection.execute(
                    """
                    CREATE TABLE IF NOT EXISTS chat_turns (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        session_id TEXT NOT NULL,
                        user_message TEXT NOT NULL,
                        assistant_message TEXT NOT NULL,
                        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )
                    """
                )
                connection.execute(
                    """
                    CREATE INDEX IF NOT EXISTS idx_chat_turns_session_id_id
                        ON chat_turns (session_id, id)
                    """
                )
            else:
                connection.executescript(
                    """
                    CREATE TABLE IF NOT EXISTS chat_turns (
                        id INTEGER PRIMARY KEY AUTOINCREMENT,
                        session_id TEXT NOT NULL,
                        user_message TEXT NOT NULL,
                        assistant_message TEXT NOT NULL,
                        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
                    );
                    CREATE INDEX IF NOT EXISTS idx_chat_turns_session_id_id
                        ON chat_turns (session_id, id);
                    """
                )
            yield connection, is_postgres
    finally:
        connection.close()


def _execute(connection, query: str, params: tuple = (), is_postgres: bool = False):
    if is_postgres:
        query = query.replace("?", "%s")
    return connection.execute(query, params)


def _select_turns(session_id: str, limit: int):
    with _connection() as (connection, is_postgres):
        return _execute(
            connection,
            """
            SELECT user_message, assistant_message
            FROM chat_turns
            WHERE session_id = ?
            ORDER BY id DESC
            LIMIT ?
            """,
            (session_id, limit),
            is_postgres,
        ).fetchall()


def _terms(text: str) -> set[str]:
    return {
        term
        for term in re.findall(r"\w{3,}", text.casefold())
        if term not in STOP_WORDS
    }


def load_memory(session_id: str, current_message: str) -> tuple[
    list[tuple[str, str]], list[tuple[str, str]]
]:
    rows = _select_turns(session_id, LONG_TERM_CANDIDATES)

    turns = [(row[0], row[1]) for row in reversed(rows)]
    recent_turns = turns[-SHORT_TERM_TURNS:]
    older_turns = turns[:-SHORT_TERM_TURNS]
    query_terms = _terms(current_message)

    ranked_turns = []
    for index, turn in enumerate(older_turns):
        user_message, assistant_message = turn
        score = len(query_terms & _terms(f"{user_message} {assistant_message}"))
        if score:
            ranked_turns.append((score, index, turn))
    relevant_turns = [
        turn
        for _, _, turn in sorted(
            ranked_turns,
            key=lambda item: (item[0], item[1]),
            reverse=True,
        )[:LONG_TERM_MATCHES]
    ]
    relevant_turns.reverse()
    return recent_turns, relevant_turns


def save_turn(session_id: str, user_message: str, assistant_message: str) -> None:
    with _connection() as (connection, is_postgres):
        _execute(
            connection,
            """
            INSERT INTO chat_turns (session_id, user_message, assistant_message)
            VALUES (?, ?, ?)
            """,
            (session_id, user_message, assistant_message),
            is_postgres,
        )


def load_history(session_id: str) -> list[ChatMessage]:
    rows = _select_turns(session_id, HISTORY_TURNS)

    messages: list[ChatMessage] = []
    for user_message, assistant_message in reversed(rows):
        messages.extend(
            [
                {"role": "user", "content": user_message},
                {"role": "assistant", "content": assistant_message},
            ]
        )
    return messages


def delete_history(session_id: str) -> None:
    with _connection() as (connection, is_postgres):
        _execute(
            connection,
            "DELETE FROM chat_turns WHERE session_id = ?",
            (session_id,),
            is_postgres,
        )


def build_prompt(
    current_message: str,
    recent_turns: list[tuple[str, str]],
    relevant_turns: list[tuple[str, str]],
) -> str:
    sections = []
    if relevant_turns:
        sections.append(
            "Relevant older conversation memory (reference only):\n"
            + "\n\n".join(_format_turn(turn) for turn in relevant_turns)
        )
    if recent_turns:
        sections.append(
            "Recent conversation history (reference only):\n"
            + "\n\n".join(_format_turn(turn) for turn in recent_turns)
        )
    sections.append(f"Current user message:\n{current_message}")
    return "\n\n".join(sections)


def _format_turn(turn: tuple[str, str]) -> str:
    user_message, assistant_message = turn
    return (
        f"User: {_limit_text(user_message)}\n"
        f"Assistant: {_limit_text(assistant_message)}"
    )


def _limit_text(text: str) -> str:
    if len(text) <= MEMORY_TEXT_LIMIT:
        return text
    return f"{text[:MEMORY_TEXT_LIMIT]} [truncated]"
